#!/usr/bin/env node
// Auto-generates PORT_MANIFEST.md: which Java classes have a mirrored TS file.
// Run: npm run port:manifest
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const JAVA = "src/main/java/com/jcloisterzone";
const TS = "src/main/ts/com/jcloisterzone";

// Packages/files we intentionally do NOT port (headless engine; no UI/AI/rendering).
const SKIP_PKGS = new Set(["ui", "ai", "debug"]);
const SKIP_FILES = new Set(["Immutable.java"]); // marker annotation

function walk(dir, ext = ".java") {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p, ext));
    else if (name.endsWith(ext)) out.push(p);
  }
  return out;
}

// Cache of TS file contents per package dir, for "folded nested class" detection.
const tsTextByPkg = new Map();
function pkgTsText(pkg) {
  if (tsTextByPkg.has(pkg)) return tsTextByPkg.get(pkg);
  let text = "";
  const dir = join(TS, pkg);
  try {
    for (const f of walk(dir, ".ts")) text += readFileSync(f, "utf8");
  } catch {
    /* no such ts dir */
  }
  tsTextByPkg.set(pkg, text);
  return text;
}

const rows = {};
let total = 0,
  ported = 0,
  folded = 0,
  missing = 0,
  skipped = 0;

for (const jp of walk(JAVA)) {
  const rel = relative(JAVA, jp); // e.g. board/Tile.java
  const parts = rel.split(sep);
  const pkg = parts[0];
  const base = parts[parts.length - 1];
  total++;
  if (SKIP_PKGS.has(pkg) || SKIP_FILES.has(base)) {
    skipped++;
    continue;
  }
  const className = base.slice(0, -5);
  const tsPath = join(TS, rel.slice(0, -5) + ".ts");
  const r = (rows[pkg] ??= { ported: [], folded: [], missing: [] });
  let exists = false;
  try {
    exists = statSync(tsPath).isFile();
  } catch {}
  if (exists) {
    r.ported.push(rel);
    ported++;
  } else {
    // folded? nested class declared inside another TS file in the same package
    const re = new RegExp(`(class|enum|interface|namespace)\\s+${className}\\b`);
    if (re.test(pkgTsText(parts.slice(0, -1).join(sep)))) {
      r.folded.push(rel);
      folded++;
    } else {
      r.missing.push(rel);
      missing++;
    }
  }
}

const todo = (() => {
  let n = 0;
  for (const f of walk(TS, ".ts")) n += (readFileSync(f, "utf8").match(/TODO\(/g) || []).length;
  return n;
})();

let md = `# Port manifest (auto-generated by scripts/port-manifest.mjs)\n\n`;
md += `Java classes: ${total} | ported: ${ported} | folded(nested): ${folded} | MISSING: ${missing} | skipped(ui/ai/debug/Immutable): ${skipped}\n`;
md += `Open TODO( ) tags in TS: ${todo}  (grep "TODO(" for staged/partial work)\n\n`;
md += `| package | ported | folded | MISSING |\n|---|--:|--:|--:|\n`;
for (const pkg of Object.keys(rows).sort()) {
  const r = rows[pkg];
  md += `| ${pkg} | ${r.ported.length} | ${r.folded.length} | ${r.missing.length} |\n`;
}
md += `\n## MISSING by package (the real to-do list)\n`;
for (const pkg of Object.keys(rows).sort()) {
  if (!rows[pkg].missing.length) continue;
  md += `\n### ${pkg} (${rows[pkg].missing.length})\n`;
  for (const r of rows[pkg].missing.sort()) md += `- [ ] ${r}\n`;
}
writeFileSync("PORT_MANIFEST.md", md);
console.log(
  `total ${total} | ported ${ported} | folded ${folded} | MISSING ${missing} | skipped ${skipped} | TODO tags ${todo}`,
);
console.log("wrote PORT_MANIFEST.md");
